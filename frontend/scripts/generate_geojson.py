def main():
    features = get_all_features()

    geojson = {
        "type": "FeatureCollection",
        "features": features
    }

    output_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                               "public", "geojson", "india-states.json")

    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(geojson, f, indent=2)

    # Report stats
    file_size = os.path.getsize(output_path)
    feature_count = len(features)
    total_coords = 0
    for feat in features:
        for polygon in feat['geometry']['coordinates']:
            for ring in polygon:
                total_coords += len(ring)

    print(f"Generated GeoJSON: {output_path}")
    print(f"File size: {file_size:,} bytes ({file_size/1024:.1f} KB)")
    print(f"Feature count: {feature_count}")
    print(f"Total coordinate points: {total_coords}")

    # Verify all 36 states/UTs
    names = [f['properties']['name'] for f in features]
    print(f"\nStates/UTs included ({len(names)}):")
    for name in sorted(names):
        print(f"  - {name}")

    # Validate codes
    expected_codes = {'LA','JK','HP','PB','CH','UK','HR','DL','RJ','UP','BR','SK','WB',
                      'JH','OD','CG','MP','GJ','MH','GA','KA','KL','TN','AP','TG',
                      'DD','AS','ML','AR','NL','MN','MZ','TR','PY','AN','LD'}
    actual_codes = {f['properties']['code'] for f in features}
    missing = expected_codes - actual_codes
    if missing:
        print(f"\nWARNING: Missing codes: {missing}")
    else:
        print(f"\nAll {len(expected_codes)} state/UT codes present!")


if __name__ == '__main__':
    main()
