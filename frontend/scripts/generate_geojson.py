import json, os, math

def make_feature(name, slug, code, capital, stype, coordinates):
    """Create a GeoJSON Feature with MultiPolygon geometry."""
    return {
        "type": "Feature",
        "properties": {
            "name": name,
            "slug": slug,
            "code": code,
            "capital": capital,
            "type": stype
        },
        "geometry": {
            "type": "MultiPolygon",
            "coordinates": coordinates
        }
    }

def close_ring(coords):
    """Ensure the ring is closed (first point == last point)."""
    if coords[0] != coords[-1]:
        coords.append(coords[0])
    return coords

